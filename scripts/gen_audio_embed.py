"""Writes WiNILL/AudioEmbed.rc: every sound the cue and BGM tables use, as RCDATA.
    python scripts/gen_audio_embed.py
Run it after adding or renaming a sound in AudioCues.inc / AudioBgm.inc.
The resource name is the path made upper-case with every non-alphanumeric
character turned into '_' (Audio.cpp builds the same name at run time).
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "WiNILL")
paths = []
for inc in ("System/AudioCues.inc", "System/AudioBgm.inc"):
    for line in open(os.path.join(ROOT, inc), encoding="utf-8"):
        if not re.match(r"\s*(CUE|BGM)\(", line):
            continue
        for p in re.findall(r'"(Resource/Audio/[^"]+)"', line):
            if p not in paths:
                paths.append(p)

missing = [p for p in paths if not os.path.isfile(os.path.join(ROOT, p))]
if missing:
    sys.exit("missing sound files:\n  " + "\n  ".join(missing))


def res_name(p):
    return re.sub(r"[^A-Z0-9]", "_", p.upper())


lines = ["// Generated by scripts/gen_audio_embed.py: do not edit by hand.",
         "// Every sound in AudioCues.inc / AudioBgm.inc, built into the exe."]
for p in paths:
    lines.append(f'{res_name(p):64s} RCDATA "{p.replace("/", chr(92) * 2)}"')
with open(os.path.join(ROOT, "AudioEmbed.rc"), "w", encoding="ascii", newline="\r\n") as f:
    f.write("\n".join(lines) + "\n")
size = sum(os.path.getsize(os.path.join(ROOT, p)) for p in paths)
print(f"{len(paths)} sounds, {size / 1e6:.1f} MB -> WiNILL/AudioEmbed.rc")
