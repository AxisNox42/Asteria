"""One-off: removes every card that needed another card first and adds the chance cards instead.

Rewrites the table in WiNILL/Entity/AugmentSynergy.h, scripts/synergy_locale.py and writes
WiNILL/Entity/SynergyChance.inc (the runtime reads that list: kind, condition, chance).
Run scripts/gen_synergy_catalog.py afterwards.
"""
import json
import re
import sys
sys.path.insert(0, 'D:/ConsoleProject/team-pinata/scripts')
from synergy_chance import CONDS, KINDS, PAIRS

ROOT = 'D:/ConsoleProject/team-pinata/'


def rd(p):
    return open(ROOT + p, 'rb').read().decode('utf-8')


def wr(p, s):
    open(ROOT + p, 'wb').write(s.encode('utf-8'))


REGEN = '--regen' in sys.argv
REMOVE = ['V_WALLCRACK', 'A_BOUNCE', 'A_PIERCE', 'A_SPLIT', 'A_BEAM', 'A_RAPID', 'A_CHARGE', 'A_ORBIT', 'A_BLAST',
          'A_CHAIN', 'A_SPREAD_MORE', 'A_NTH_FAST', 'A_TRAIL', 'A_TRAIL_BLAST', 'A_RETURN', 'A_HOVER_BLAST',
          'A_GLASS_SHARD', 'A_SHIELD_BLAST', 'A_SHIELD_COUNTER', 'A_HP_WOUND', 'A_CRIT', 'A_STILL', 'A_WALL',
          'A_BURN', 'A_MARK', 'A_BURST', 'A_PULL', 'T_BOUNCECHAIN', 'A_DICE', 'A_STORE', 'A_GROW', 'A_ERASE',
          'A_TRAP', 'A_COMBO', 'A_SWAP', 'A_DASHCHAIN', 'A_ENCORE', 'A_RHYTHM', 'A_LOB', 'A_SEEK', 'A_NTH_SPLIT',
          'Y_REAPER']

cond = {c[0]: c for c in CONDS}
kind = {k[0]: k for k in KINDS}

# ── table ──
p = 'WiNILL/Entity/AugmentSynergy.h'
h = rd(p)
nl = '\r\n' if '\r\n' in h else '\n'
lines = h.split(nl)
out = []
i = 0
removed = 0
while i < len(lines):
    ln = lines[i]
    m = re.match(r'    \{"([A-Z_]+)",', ln)
    if m and m.group(1) in REMOVE:
        removed += 1
        i += 1
        while i < len(lines) and not (lines[i].startswith('    {"') or lines[i].startswith('    //') or lines[i].startswith('    };')):
            i += 1
        continue
    out.append(ln)
    i += 1
if REGEN:
    # drop the chance rows and the comment line written by an earlier run
    cleaned = []
    j = 0
    while j < len(out):
        if re.match(r'    \{"P_', out[j]):
            j += 2
            continue
        if out[j].startswith('    // ── 확률 카드'):
            j += 1
            continue
        cleaned.append(out[j])
        j += 1
    out = cleaned
else:
    assert removed == len(REMOVE), (removed, len(REMOVE))
h = nl.join(out)

rows = []
inc = []
loc = []
for c, k, strength in PAIRS:
    cc, kk = cond[c], kind[k]
    up = cc[7]
    pct = int(min(100, max(5, round(strength / up * 100 / 5) * 5)))
    eff = pct / 100.0 * up
    code = 'P_%s_%s' % (c.upper(), k.upper())
    name = '%s %s' % (cc[1], kk[1])
    rule = '%s %s' % (cc[4], kk[4].format(p=pct))
    if k == 'Crit':
        fx = 'Fx{}.crit_(%.3ff)' % (eff * 1.0)
    elif k == 'Extra':
        fx = 'Fx{}.bullets_(%.3ff)' % (1.0 + eff)
    else:
        mult = {'Pierce': 1.1, 'Bounce': 1.0, 'Split': 1.3, 'Blast': 1.1}[k]
        fx = 'Fx{}.dmgAdd_(%.3ff)' % (eff * mult)
    rows.append('    {"%s", "%s", "%s", Rar::Common, Role::Chance,\n        T_NONE, 0, false, %s},' % (code, name, rule, fx))
    inc.append('CH(%s, %s, %s, %d)' % (code, k, c, pct))
    loc.append((code, '%s %s' % (cc[2], kk[2]), '%s%s' % (cc[3], kk[3]),
                '%s %s' % (cc[5], kk[5].format(p=pct)), '%s%s' % (cc[6], kk[6].format(p=pct))))

end_marker = '    };' + nl + '    return t;'
assert h.count(end_marker) == 1
h = h.replace(end_marker, '    // ── 확률 카드: 다른 카드 없이 혼자 작동, 조건을 만족하는 동안 한 가지 확률이 오름 ──' + nl +
              nl.join(r.replace('\n', nl) for r in rows) + nl + end_marker)
if not REGEN:
    assert h.count('enum class Role { Frame, Verb, Trigger, Amp, Cost, Guard };') == 1
    h = h.replace('enum class Role { Frame, Verb, Trigger, Amp, Cost, Guard };',
                  'enum class Role { Frame, Verb, Trigger, Amp, Cost, Guard, Chance };')
    old = 'static const char* n[] = { "프레임", "동사", "트리거", "증폭", "대가", "보호" };'
    assert h.count(old) == 1
    h = h.replace(old, 'static const char* n[] = { "프레임", "동사", "트리거", "증폭", "대가", "보호", "확률" };')
wr(p, h)

# ── locale ──
p = 'scripts/synergy_locale.py'
s = rd(p)
nl2 = '\r\n' if '\r\n' in s else '\n'
if REGEN:
    s = re.sub(r'    "P_[A-Z_]+": \(.*\),\r?\n', '', s)
    s = s.replace('    # ── chance cards ──' + nl2, '')
for code in ([] if REGEN else REMOVE):
    s, n = re.subn(r'    "' + code + r'": \(.*\),\r?\n', '', s)
    assert n == 1, code
add = ''.join('    %s: (%s, %s, %s, %s),%s' % (json.dumps(c), json.dumps(a, ensure_ascii=False), json.dumps(b, ensure_ascii=False),
                                            json.dumps(d, ensure_ascii=False), json.dumps(e, ensure_ascii=False), nl2)
              for c, a, b, d, e in loc)
idx = s.rindex('}')
s = s[:idx] + '    # ── chance cards ──' + nl2 + add + s[idx:]
wr(p, s)

# ── runtime list ──
wr('WiNILL/Entity/SynergyChance.inc',
   '// Generated by scripts/apply_chance_cards.py (data: scripts/synergy_chance.py). CH(code, kind, condition, chance %).\n' +
   '\n'.join(inc) + '\n')
print('removed', removed, 'added', len(rows))
