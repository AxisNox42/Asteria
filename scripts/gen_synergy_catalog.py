"""Generates the two include files that register the synergy cards in the game:

    WiNILL/Entity/SynergyCodes.inc        one SYN(code) per card, in table order (no F_BASIC)
    WiNILL/Entity/SynergyCatalogRows.inc  one AUG(...) catalog row per card

The numbers and the Korean text come from WiNILL/Entity/AugmentSynergy.h (the table the balance
test checks). English and Japanese come from scripts/synergy_locale.py; a card without an entry
there falls back to the Korean text. Run after editing the table or the locale file:

    python scripts/gen_synergy_catalog.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
from synergy_locale import LOC  # noqa: E402

RAR = {"Common": "COMMON", "Rare": "RARE", "Epic": "EPIC", "Legendary": "LEGENDARY", "Mythic": "MYTHIC"}


def wide(s):
    return 'L"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    src = (ROOT / "WiNILL" / "Entity" / "AugmentSynergy.h").read_text(encoding="utf-8")
    body = src[src.index("static const std::vector<Aug> t = {"):src.index("    };\n    return t;")]
    rows = re.findall(r'^    \{"(\w+)",\s*"([^"]*)",\s*"([^"]*)",\s*Rar::(\w+),\s*Role::(\w+)', body, re.M)
    assert rows and rows[0][0] == "F_BASIC", "the first table row must be the bare gun"
    rows = rows[1:]
    codes, cat = [], []
    missing = []
    for code, kr, rule, rar, role in rows:
        codes.append(f"SYN({code})\n")
        en_name, jp_name, en_rule, jp_rule = LOC.get(code, (None, None, None, None))
        if en_name is None:
            missing.append(code)
            en_name, jp_name, en_rule, jp_rule = kr, kr, rule, rule
        cat.append(
            f"    AUG(SYN_{code}, {RAR[rar]}, false,\n"
            f"        {wide(kr)}, {wide(en_name)}, {wide(jp_name)},\n"
            f"        {wide(rule)},\n        {wide(en_rule)},\n        {wide(jp_rule)}),\n")
    out = ROOT / "WiNILL" / "Entity"
    (out / "SynergyCodes.inc").write_text(
        "// Generated by scripts/gen_synergy_catalog.py from AugmentSynergy.h. Do not edit.\n" + "".join(codes),
        encoding="utf-8", newline="\n")
    (out / "SynergyCatalogRows.inc").write_text(
        "// Generated by scripts/gen_synergy_catalog.py from AugmentSynergy.h and synergy_locale.py. Do not edit.\n"
        + "".join(cat), encoding="utf-8", newline="\n")
    print(f"{len(rows)} cards registered; {len(missing)} without English/Japanese text (Korean shown)")


if __name__ == "__main__":
    main()
